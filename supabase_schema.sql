-- STORAGE (TO'LOV CHEKLARI RASMLARI UCHUN BUCKET)
-- ==============================================================================

INSERT INTO storage.buckets (id, name, public)
VALUES ('receipts', 'receipts', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Public access to receipts storage" ON storage.objects;
CREATE POLICY "Public access to receipts storage" ON storage.objects
FOR ALL TO anon, authenticated
USING (bucket_id = 'receipts')
WITH CHECK (bucket_id = 'receipts');

DROP POLICY IF EXISTS "Allow public to view buckets" ON storage.buckets;
CREATE POLICY "Allow public to view buckets" ON storage.buckets
FOR SELECT TO anon, authenticated
USING (public = true);
