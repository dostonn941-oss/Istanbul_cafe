-- 1. KATEGORIYALAR JADVALI (menu_categories)
CREATE TABLE IF NOT EXISTS public.menu_categories (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    sticker TEXT,
    sort_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. TAOMLAR MENYUSI JADVALI (menu_items)
CREATE TABLE IF NOT EXISTS public.menu_items (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    price BIGINT NOT NULL,
    category TEXT NOT NULL REFERENCES public.menu_categories(id) ON DELETE CASCADE,
    image_url TEXT,
    is_available BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. BUYURTMALAR JADVALI (orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL DEFAULT 'new',
    timestamp TEXT NOT NULL,
    customer TEXT NOT NULL,
    phone TEXT NOT NULL,
    service TEXT NOT NULL DEFAULT 'pickup',
    location TEXT DEFAULT '',
    payment TEXT DEFAULT '',
    card_number TEXT,
    card_owner TEXT,
    payment_confirmed BOOLEAN DEFAULT false,
    receipt_url TEXT,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    total BIGINT NOT NULL DEFAULT 0,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    tg_user_id BIGINT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 4. KAFE SOZLAMALARI JADVALI (cafe_settings)
CREATE TABLE IF NOT EXISTS public.cafe_settings (
    id INT PRIMARY KEY DEFAULT 1,
    card_number TEXT DEFAULT '8600 1234 5678 9012',
    card_owner TEXT DEFAULT 'Korolevskiy Center',
    is_open BOOLEAN DEFAULT true,
    cafe_name TEXT DEFAULT 'Korolevskiy Center',
    updated_at TIMESTAMPTZ DEFAULT now()
);

