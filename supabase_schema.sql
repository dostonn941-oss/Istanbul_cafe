-- ==============================================================================
-- XAVFSIZLIK VA RUXSATLAR (ROW LEVEL SECURITY - RLS)
-- ==============================================================================

ALTER TABLE public.menu_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cafe_settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all for menu_categories" ON public.menu_categories;
CREATE POLICY "Allow all for menu_categories" ON public.menu_categories FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all for menu_items" ON public.menu_items;
CREATE POLICY "Allow all for menu_items" ON public.menu_items FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all for orders" ON public.orders;
CREATE POLICY "Allow all for orders" ON public.orders FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all for cafe_settings" ON public.cafe_settings;
CREATE POLICY "Allow all for cafe_settings" ON public.cafe_settings FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

